export interface Run { x: number; y: number; w: number }

export function layout(text: string, bold = false) {
  const rows: string[] = Array.from({ length: 9 }, () => '');
  let first = true;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    for (let r = 0; r < 9; r++) {
      let row = g[r];
      if (bold) {
        const arr = row.split('').concat(['.']);
        for (let c = 0; c < row.length; c++) if (row[c] === '#') arr[c + 1] = '#';
        row = arr.join('');
      }
      rows[r] += (first ? '' : '.') + row;
    }
    first = false;
  }
  const runs: Run[] = [];
  for (let r = 0; r < 9; r++) {
    const m = rows[r];
    let c = 0;
    while (c < m.length) {
      if (m[c] === '#') {
        let e = c;
        while (e < m.length && m[e] === '#') e++;
        runs.push({ x: c, y: r, w: e - c });
        c = e;
      } else c++;
    }
  }
  return { cols: rows[0].length, rows: 9, runs };
}

export function mulberry(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}